function convertKeyboardText(text, direction) {
    var map = keyboardMaps[direction];
    if (!map) throw new Error("Unknown conversion direction: " + direction);
    // NFC also accepts accents stored as a base letter + combining mark.
    return Array.from(text.normalize("NFC")).map(function (character) {
        return Object.prototype.hasOwnProperty.call(map, character) ? map[character] : character;
    }).join("");
}

